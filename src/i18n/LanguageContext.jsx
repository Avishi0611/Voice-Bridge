const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('voicebridge-language') || 'en')
  const selected = languages.find((item) => item.code === language) || languages[0]

  useEffect(() => {
    localStorage.setItem('voicebridge-language', selected.code)
    document.documentElement.lang = selected.code
  }, [selected.code])

  const value = useMemo(() => ({
    language: selected.code,
    languageName: selected.label,
    speechLanguage: selected.speech,
    languages,
    setLanguage,
    t: (key) => translations[selected.code]?.[key] || translations.hi?.[key] || translations.en[key] || key,
  }), [selected.code, selected.label, selected.speech])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider')
  return context
}

export function LanguageSelector({ className = '' }) {
  const { language, languages: supportedLanguages, setLanguage, t } = useLanguage()
  return (
    <label className={`relative block ${className}`}>
      <span className="sr-only">{t('language')}</span>
      <select
        value={language}
        onChange={(event) => setLanguage(event.target.value)}
        aria-label={t('language')}
        className="w-full appearance-none rounded-xl border border-slate-200/90 bg-white/95 py-2 pl-3 pr-7 text-xs font-bold text-slate-700 shadow-sm outline-none transition focus:border-violet-500 focus:ring-2 focus:ring-violet-100 cursor-pointer"
      >
        {supportedLanguages.map((item) => (
          <option key={item.code} value={item.code}>
            {item.label}
          </option>
        ))}
      </select>
      <span className="pointer-events-none absolute right-2.5 top-1/2 -translate-y-1/2 text-[10px] text-slate-400">
        ▼
      </span>
    </label>
  )
}

